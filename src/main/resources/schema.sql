-- DDL (schema) script
create table page (
  page_id bigint generated by default as identity,
  page_name varchar(255) not null,
  primary key (page_id)
);

create table page_tab (
  tab_id bigint generated by default as identity,
  tab_name varchar(255) not null,
  page_id bigint not null,
  primary key (tab_id),
  constraint page_tab_fk1 foreign key (page_id) references page (page_id)
);

create table split_ratio (
  split_ratio_name varchar(32) not null,
  split_ratio_title varchar(255) not null,
  primary key (split_ratio_name)
);

create table page_section (
  section_id bigint generated by default as identity,
  section_name varchar(255) not null,
  section_index int not null,
  section_split_ratio varchar(32) not null,
  tab_id bigint not null,
  primary key (section_id),
  constraint page_section_fk1 foreign key (section_split_ratio) references split_ratio (split_ratio_name),
  constraint page_section_fk2 foreign key (tab_id) references page_tab (tab_id)
);

create table page_sub_section (
  sub_section_id bigint generated by default as identity,
  sub_section_name varchar(255) not null,
  section_id bigint not null,
  primary key (sub_section_id),
  constraint page_sub_section_fk1 foreign key (section_id) references page_section (section_id)
);

create table series_data (
  series_id bigint generated by default as identity,
  series_date date,
  series_value numeric(38,2),
  series_title varchar(255) not null,
  primary key (series_id)
);
